export function textWidth(text: string): number {
	return text.length === 0 ? 0 : text.length * ADVANCE - 1;
}

/** Render a line of text into a tinted offscreen canvas. */
export function renderText(text: string, color: string): OffscreenCanvas {
	const lower = text.toLowerCase();
	const out = new OffscreenCanvas(
		Math.max(1, textWidth(lower)),
		GLYPH_H,
	);
	const ctx = out.getContext("2d")!;
	ctx.fillStyle = color;
	let cx = 0;
	for (const ch of lower) {
		const glyph = GLYPHS[ch] ?? GLYPHS["."]!;
		for (let y = 0; y < GLYPH_H; y++) {
			const row = glyph[y]!;
			for (let x = 0; x < GLYPH_W; x++) {
				if (row[x] === "1") ctx.fillRect(cx + x, y, 1, 1);
			}
		}
		cx += ADVANCE;
	}
	return out;
}
